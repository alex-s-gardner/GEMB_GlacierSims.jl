# Write data/shaw2025_glacier_bands.csv.gz: the glacier area of every glacier in the Shaw et al. (2025)
# decoupling table (vendored in GEMB_ClimateForcing) in each 100 m elevation band of the project's
# hypsometry, from the RGI 6.0 hypsometry files (`*_hypso.csv`, 50 m bins in per mille of the glacier
# area). Read by `shaw_glacier_bands`.
#
#   julia --project=. scripts/make_shaw_glacier_bands.jl <directory holding the 19 RGI 6.0 *_hypso.csv>
#
# The RGI 6.0 region 01 hypsometry file labels its glaciers RGI50-01.*; region 01 kept its RGI 5.0
# numbering in RGI 6.0, so those ids are read as RGI60-01.*. A glacier without hypsometry (any bin
# negative, the RGI missing-value code, or all bins zero) is left out and counted.
using GEMB_ClimateForcing
import CodecZlib

const OUT = normpath(joinpath(@__DIR__, "..", "data", "shaw2025_glacier_bands.csv.gz"))

function main(dir)
    t = GEMB_ClimateForcing.glacier_decoupling_table()
    index = Dict(id => i for (i, id) in enumerate(t.rgi_id))
    rows = Vector{Tuple{String,String}}()
    matched = Dict{Int,Int}(); no_hypsometry = Dict{Int,Int}()
    files = sort(filter(endswith("_hypso.csv"), readdir(dir)))
    length(files) == 19 || error("expected the 19 RGI 6.0 regional hypsometry files in $dir, found $(length(files))")
    for f in files
        lines = readlines(joinpath(dir, f))
        header = strip.(split(lines[1], ','))
        header[1:3] == ["RGIId", "GLIMSId", "Area"] || error("unexpected header in $f: $(header[1:3])")
        centers = parse.(Int, header[4:end])
        all(c -> mod(c, 50) == 25, centers) || error("$f: bins are not 50 m bins centred at 25 m")
        lo = [fld(c, 100) * 100 for c in centers]
        for line in lines[2:end]
            isempty(strip(line)) && continue
            fs = strip.(split(line, ','))
            id = replace(fs[1], r"^RGI50-01\." => "RGI60-01.")
            i = get(index, id, 0)
            i == 0 && continue
            r = t.region[i]
            p = parse.(Int, fs[4:end])
            length(p) == length(centers) || error("$f: row $id has $(length(p)) bins, header $(length(centers))")
            if any(<(0), p) || sum(p) == 0
                no_hypsometry[r] = get(no_hypsometry, r, 0) + 1
                continue
            end
            area = parse(Float64, fs[3])
            bands = Dict{Int,Float64}()
            for (j, pj) in pairs(p)
                pj > 0 && (bands[lo[j]] = get(bands, lo[j], 0.0) + area * pj / sum(p))
            end
            keys_sorted = sort!(collect(keys(bands)))
            push!(rows, (id, join((t.rgi_id[i], round(t.lat[i]; digits = 5), round(t.lon[i]; digits = 5),
                                   t.k[i], area, join(keys_sorted, ';'),
                                   join((round(bands[b]; digits = 6) for b in keys_sorted), ';')), ',')))
            matched[r] = get(matched, r, 0) + 1
        end
    end
    sort!(rows; by = first)
    n_shaw = Dict(r => count(==(r), t.region) for r in unique(t.region))
    open(CodecZlib.GzipCompressorStream, OUT, "w") do io
        println(io, "# Glacier area per 100 m elevation band of the glaciers in the Shaw et al. (2025)")
        println(io, "# per-glacier decoupling table (GEMB_ClimateForcing data/shaw2025_glacier_decoupling.csv.gz),")
        println(io, "# from the RGI 6.0 hypsometry files (RGI Consortium 2017, doi:10.7265/N5-RGI-60).")
        println(io, "# Generated by scripts/make_shaw_glacier_bands.jl.")
        println(io, "#")
        println(io, "# rgi_id        : RGI 6.0 identifier")
        println(io, "# lat, lon      : glacier centroid of the Shaw table, decimal degrees (lon -180..180)")
        println(io, "# k             : Shaw et al. (2025) glacier-mean decoupling factor")
        println(io, "# area_km2      : RGI 6.0 glacier area")
        println(io, "# band_lo       : ';'-separated lower edges (m) of the 100 m bands [lo, lo + 100) holding ice")
        println(io, "# band_area_km2 : ';'-separated glacier area in those bands; sums to area_km2")
        println(io, "rgi_id,lat,lon,k,area_km2,band_lo,band_area_km2")
        for (_, r) in rows
            println(io, r)
        end
    end
    for r in sort(collect(keys(n_shaw)))
        println("region $(lpad(r, 2, '0')): $(get(matched, r, 0)) of $(n_shaw[r]) Shaw glaciers written, " *
                "$(get(no_hypsometry, r, 0)) without hypsometry")
    end
    println("wrote $(length(rows)) glaciers to $OUT")
end

main(only(ARGS))
